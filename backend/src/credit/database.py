"""Async PostgreSQL transaction boundary backed by sqlc generated queries."""
from __future__ import annotations

import logging
import inspect
import uuid
from contextlib import asynccontextmanager
from typing import Any
from uuid import UUID

from psycopg.types.json import Jsonb
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncConnection, AsyncEngine, create_async_engine

from credit.migrate import migrations_current

LOG = logging.getLogger(__name__)

# Allowlisting prevents user data or a mistaken service name from becoming SQL.
TABLES = frozenset({
    "users", "auth_sessions", "refresh_tokens", "companies", "company_members",
    "loan_products", "applications", "documents", "application_snapshots",
    "information_requests", "check_runs", "scoring_results", "credit_decisions",
    "offers", "application_events", "audit_events", "jobs", "upload_reservations",
})


def _identifier(value: Any) -> UUID:
    return value if isinstance(value, UUID) else UUID(str(value))


def _payload(row: Any) -> dict[str, Any] | None:
    if row is None:
        return None
    if isinstance(row, dict):
        value = row.get("payload", row)
    elif hasattr(row, "payload"):
        value = row.payload
    else:
        try:
            value = row["payload"]
        except (KeyError, TypeError, IndexError):
            value = row
    return dict(value) if isinstance(value, dict) else value


class Store:
    """Transaction-scoped operations whose SQL is generated by sqlc."""

    def __init__(self, connection: AsyncConnection, querier: Any):
        self.connection = connection
        self.querier = querier

    @staticmethod
    def _table(name: str) -> str:
        if name not in TABLES:
            raise ValueError(f"Unknown database collection: {name}")
        return name

    async def get(self, table: str, id: Any, *, lock: bool = False) -> dict[str, Any] | None:
        table = self._table(table)
        query = getattr(self.querier, f"{'lock' if lock else 'get'}_{table}")
        return _payload(await query(id=_identifier(id)))

    async def list(self, table: str, **filters: Any) -> list[dict[str, Any]]:
        table = self._table(table)
        # JSONB is intentionally wrapped at the Psycopg boundary: sqlc's typed
        # generated method accepts Any for jsonb and a naked dict is not adapted.
        rows = getattr(self.querier, f"list_{table}")(filters=Jsonb(filters))
        if inspect.isawaitable(rows):
            rows = await rows
        records: list[dict[str, Any]] = []
        if hasattr(rows, "__aiter__"):
            async for row in rows:
                record = _payload(row)
                if record is not None:
                    records.append(record)
        else:
            for row in rows:
                record = _payload(row)
                if record is not None:
                    records.append(record)
        return records

    async def insert(self, table: str, row: dict[str, Any]) -> dict[str, Any]:
        table = self._table(table)
        payload = dict(row)
        created = await getattr(self.querier, f"insert_{table}")(
            id=_identifier(payload["id"]), payload=Jsonb(payload)
        )
        value = _payload(created)
        if value is None:
            raise RuntimeError(f"Insert into {table} did not return the saved payload")
        return value

    async def save(self, table: str, row: dict[str, Any]) -> dict[str, Any]:
        table = self._table(table)
        payload = dict(row)
        updated = await getattr(self.querier, f"save_{table}")(
            payload=Jsonb(payload), id=_identifier(payload["id"])
        )
        value = _payload(updated)
        if value is None:
            raise RuntimeError(f"Cannot update missing row in {table}")
        return value

    async def delete(self, table: str, id: Any) -> None:
        table = self._table(table)
        await getattr(self.querier, f"delete_{table}")(id=_identifier(id))

    async def claim_job(self, lease_seconds: float) -> dict[str, Any] | None:
        claim = await self.querier.claim_jobs(lease_seconds=lease_seconds, claim_id=uuid.uuid4())
        return _payload(claim)


class Database:
    def __init__(self, url: str, *, engine: AsyncEngine | None = None):
        self.engine = engine or create_async_engine(url, pool_pre_ping=True)
        self._owns_engine = engine is None

    @asynccontextmanager
    async def transaction(self):
        try:
            async with self.engine.begin() as connection:
                # Generated modules are imported lazily so database module can
                # be imported by tooling even before code generation.
                from creditdb.repository import AsyncQuerier

                yield Store(connection, AsyncQuerier(connection))
        except IntegrityError as exc:
            # The engine context has rolled the transaction back before this
            # translation, so an API error can never commit partial writes.
            code = getattr(exc.orig, "sqlstate", None) or getattr(getattr(exc.orig, "diag", None), "sqlstate", None)
            constraint = getattr(getattr(exc.orig, "diag", None), "constraint_name", None)
            if code in {"23505", "23503", "23514", "23P01"}:
                from credit.common import ApiError

                detail = []
                if constraint:
                    detail = [{"field": "resource", "message": "Запись нарушает ограничение целостности данных."}]
                raise ApiError(409, "Запись конфликтует с существующими данными.", detail) from None
            LOG.exception("Database integrity error", extra={"sqlstate": code})
            raise

    async def check_ready(self) -> bool:
        try:
            # The migration ledger query is both the connectivity check and the
            # schema-version check; it uses only the migration runner boundary.
            return await migrations_current(self.engine.url.render_as_string(hide_password=False), engine=self.engine)
        except Exception:
            LOG.exception("Database readiness check failed")
            return False

    async def close(self) -> None:
        if self._owns_engine:
            await self.engine.dispose()
